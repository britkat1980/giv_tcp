"""Enforce the per-file line-and-branch coverage target from coverage.py JSON."""
import argparse
import json


def below_target(report, minimum):
    # Use the unrounded percentage so 69.995% cannot pass a 70% threshold.
    return [(name, data['summary']['percent_covered'])
            for name, data in sorted(report['files'].items())
            if data['summary']['percent_covered'] < minimum]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('report', help='JSON generated by python -m coverage json')
    parser.add_argument('--minimum', type=float, default=70)
    args = parser.parse_args()
    with open(args.report, encoding='utf-8') as source:
        report = json.load(source)
    failures = below_target(report, args.minimum)
    for name, percent in failures:
        print(f'{name}: {percent:.2f}% (required: {args.minimum:g}%)')
    if failures:
        print(f'{len(failures)} files below the coverage target')
        return 1
    print(f'All {len(report["files"])} files meet {args.minimum:g}% line-and-branch coverage')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
